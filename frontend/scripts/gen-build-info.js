const { execSync } = require('child_process');
const { writeFileSync } = require('fs');
const { join } = require('path');
const { version } = require('../package.json');

let sha = 'dev';
try {
  sha = execSync('git rev-parse --short HEAD', { cwd: join(__dirname, '..') })
    .toString()
    .trim();
} catch {
  // not in a git repo or git not available
}

const content =
  `// Auto-generated by scripts/gen-build-info.js — do not edit\n` +
  `export const BUILD_VERSION = '${version}';\n` +
  `export const BUILD_SHA = '${sha}';\n`;

writeFileSync(join(__dirname, '../src/app/build-info.ts'), content);
console.log(`build-info.ts generated: v${version} (${sha})`);
